#!/usr/bin/env python3
"""host_test_labvid.py — run the EXACT device decoder on the real asset.

Compiles main/labvid.c (unmodified, pure C99) with gcc together with a
generated harness, decodes every frame of main/base.vlb2, and compares
per-frame FNV-1a hashes against the Python mirror of the decoder
(verify_assets.decode_frame). Also checks:

  - the row iterator (same decoder, ring free once the frame is staged)
    streams frame 0 to the same bytes the main decoder staged
  - re-staging an earlier frame after the cache moved on still decodes

Exit code 0 = the device code and the Python mirror agree byte-for-byte
on every frame of the real blob.
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = HERE.parent / "main"
sys.path.insert(0, str(HERE))
from verify_assets import decode_frame  # noqa: E402

HARNESS = r"""
/* test_labvid_host.c — generated by host_test_labvid.py (host gate). */
#include <stdio.h>
#include <stdlib.h>
#include "labvid.h"

static unsigned fnv1a(const unsigned char *p, unsigned long n, unsigned h)
{
    while (n--) {
        h ^= *p++;
        h *= 16777619u;
    }
    return h;
}

int main(int argc, char **argv)
{
    if (argc != 2) {
        return 2;
    }
    FILE *f = fopen(argv[1], "rb");
    if (!f) {
        return 2;
    }
    fseek(f, 0, SEEK_END);
    long len = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *buf = malloc((size_t)len);
    if (fread(buf, 1, (size_t)len, f) != (size_t)len) {
        return 2;
    }
    fclose(f);

    if (!labvid_open(buf, (unsigned)len)) {
        printf("open FAILED\n");
        return 1;
    }
    printf("frames %lu\n", (unsigned long)labvid_frames());

    unsigned all = 2166136261u;
    unsigned first = 0;
    for (unsigned long i = 0; i < labvid_frames(); i++) {
        const unsigned char *fr = labvid_stage((unsigned)i);
        if (!fr) {
            printf("stage %lu FAILED\n", i);
            return 1;
        }
        unsigned h = fnv1a(fr, 480ul * 320ul, 2166136261u);
        if (i == 0) {
            first = h;
        }
        all = fnv1a(fr, 480ul * 320ul, all);
        printf("frame %lu %08x\n", i, h);
    }
    printf("combined %08x\n", all);

    /* row iterator (same decoder, ring free after staging): stream
     * frame 0 row by row, hash must match the staged frame 0 */
    if (!labvid_rows_begin(0)) {
        printf("rows_begin FAILED\n");
        return 1;
    }
    unsigned hi = 2166136261u;
    unsigned char row[480];
    for (int y = 0; y < 320; y++) {
        if (!labvid_rows_next(row)) {
            printf("rows_next FAILED at %d\n", y);
            return 1;
        }
        hi = fnv1a(row, 480, hi);
    }
    printf("iterator0 %08x\n", hi);
    printf("iter-matches-frame0 %s\n", hi == first ? "OK" : "MISMATCH");

    /* bounds + cache: out-of-range is NULL, re-stage still exact
     * (hash frame 3 BEFORE re-staging: both calls return the same
     * staging buffer, so frame 0's decode would overwrite it) */
    if (labvid_stage(labvid_frames()) != NULL) {
        printf("bounds FAILED\n");
        return 1;
    }
    const unsigned char *a = labvid_stage(3);
    unsigned h3 = fnv1a(a, 480ul * 320ul, 2166136261u);
    const unsigned char *b = labvid_stage(0);
    unsigned h0 = fnv1a(b, 480ul * 320ul, 2166136261u);
    printf("restage %s\n", (h0 == first && h3 != first) ? "OK" : "MISMATCH");
    free(buf);
    return 0;
}
"""


def fnv1a(data, h=2166136261):
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def main():
    src = MAIN / "base.vlb2"
    if not src.exists():
        print("base.vlb2 missing — run tools/encode_lab.py first")
        return 1

    harness = Path("/tmp/test_labvid_host.c")
    harness.write_text(HARNESS)
    subprocess.run(
        ["gcc", "-O2", "-Wall", "-Wextra", "-std=c99", "-I", str(MAIN),
         str(MAIN / "labvid.c"), str(harness), "-o", "/tmp/test_labvid"],
        check=True)
    print("compiled labvid.c (unmodified device decoder) + harness")

    out = subprocess.run(["/tmp/test_labvid", str(src)],
                         capture_output=True, text=True, check=True).stdout
    lines = out.strip().splitlines()
    hashes = {}
    combined = it0 = None
    iter_ok = restage_ok = "?"
    for ln in lines:
        p = ln.split()
        if not p:
            continue
        if p[0] == "frame":
            hashes[int(p[1])] = int(p[2], 16)
        elif p[0] == "combined":
            combined = int(p[1], 16)
        elif p[0] == "iterator0":
            it0 = int(p[1], 16)
        elif p[0] == "iter-matches-frame0":
            iter_ok = p[1]
        elif p[0] == "restage":
            restage_ok = p[1]

    n = len(hashes)
    print(f"C decoder staged {n} frames")

    d = src.read_bytes()
    nf = int.from_bytes(d[8:10], "little")
    if nf != n:
        print(f"FAIL: blob says {nf} frames, C says {n}")
        return 1
    table = 10 + 4 * (nf + 1)

    bad = 0
    allh = 2166136261
    for i in range(nf):
        s = table + int.from_bytes(d[10 + 4 * i:14 + 4 * i], "little")
        e = table + int.from_bytes(d[10 + 4 * (i + 1):14 + 4 * (i + 1)], "little")
        fr = decode_frame(d[s:e], 480, 320)
        h = fnv1a(fr)
        allh = fnv1a(fr, allh)
        if h != hashes[i]:
            bad += 1
            if bad <= 3:
                print(f"  frame {i}: C {hashes[i]:08x} vs Python {h:08x}")
    print(f"per-frame hash compare: {n - bad}/{n} match")

    ok = True
    if bad:
        print("FAIL: device decoder and Python mirror disagree")
        ok = False
    if combined != allh:
        print(f"FAIL: combined hash C {combined:08x} vs Python {allh:08x}")
        ok = False
    else:
        print(f"combined hash: {combined:08x} OK")
    if it0 != hashes.get(0):
        print("FAIL: iterator frame-0 hash mismatch")
        ok = False
    else:
        print("row iterator frame 0: identical to staged frame 0")
    if iter_ok != "OK":
        print("FAIL: C-side iterator self-check")
        ok = False
    if restage_ok != "OK":
        print("FAIL: C-side re-stage self-check")
        ok = False
    if nf > 3:
        print("bounds + cache re-stage: OK")

    print("\nHOST GATE " + ("PASSED" if ok else "FAILED"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
